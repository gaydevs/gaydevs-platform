// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest'
import { cleanup, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { ApplicationPage } from './ApplicationPage'
import * as api from './api'
import { emptyFields, handleValue, matchingSuggestions, platformRoute, progress } from './presentation'
import type { Session } from './api'
vi.mock('./api',()=>({getConfig:vi.fn(),getTerms:vi.fn(),getCandidate:vi.fn(),issueCode:vi.fn(),verifyCode:vi.fn(),saveStep:vi.fn(),submitApplication:vi.fn(),exitCandidate:vi.fn()}))
vi.mock('./Turnstile',()=>({Turnstile:({onToken}:{onToken:(v:string)=>void})=><button type="button" onClick={()=>onToken('test-token')}>validar antispam</button>}))
const terms={version:'v1',privacy_notice:'Aviso de teste',consents:['gay_dev','community','values','sfw','nsfw','personal_data','external_profiles'].map(key=>({key,version:'v1',text:key}))}
const draft:Session={status:'draft',current_step:'identification',revision:1,fields:{...emptyFields,email:'test@example.test'},whatsapp_url:'https://wa.me/5511999999999',consents:[]}
beforeEach(()=>{
  vi.mocked(api.getConfig).mockResolvedValue({enabled:true,sitekey:'test',cooldown:60})
  vi.mocked(api.getTerms).mockResolvedValue(terms)
  vi.mocked(api.getCandidate).mockResolvedValue(null)
})
afterEach(()=>{cleanup();vi.resetAllMocks()})
const page=()=>render(<ApplicationPage home="/gaydevs/platform/" onLogin={vi.fn()} onMemberRefresh={vi.fn().mockResolvedValue(null)}/>)
test('route base, fixed prefixes, accent insensitive search and persistent progress',()=>{
  expect(platformRoute('/gaydevs/platform/admin/applications/uuid').path('polls')).toBe('/gaydevs/platform/polls')
  expect(platformRoute('/gaydevs/platform/polls/foo').relative).toBe('polls/foo')
  expect(handleValue('linkedin','https://www.linkedin.com/in/example/')).toBe('example')
  expect(handleValue('github','@example')).toBe('example')
  expect(matchingSuggestions('GRÍNDR')).toEqual(['App de relacionamento (Tinder, Scruff, Grindr etc.)'])
  expect(progress(draft,false)).toBe(45)
  expect(progress({...draft,status:'pending'},false)).toBe(100)
})
test('public wizard shows privacy before email and requires antispam, then restores after OTP',async()=>{
  const ui=userEvent.setup()
  vi.mocked(api.issueCode).mockResolvedValue({otp_request_id:'otp',expires_at:new Date(Date.now()+600000).toISOString()})
  vi.mocked(api.verifyCode).mockResolvedValue({status:'draft'})
  page()
  expect(await screen.findByText('Aviso de teste')).toBeVisible()
  expect(screen.queryByText('falar com o scrum master')).not.toBeInTheDocument()
  await ui.type(screen.getByLabelText('E-mail'),'test@example.test')
  expect(screen.getByRole('button',{name:'enviar código'})).toBeDisabled()
  await ui.click(screen.getByRole('button',{name:'validar antispam'}))
  await ui.click(screen.getByRole('button',{name:'enviar código'}))
  expect(await screen.findByText('20%')).toBeVisible()
  expect(api.issueCode).toHaveBeenCalledWith('test@example.test','test-token')
  vi.mocked(api.getCandidate).mockResolvedValue(draft)
  await ui.type(screen.getByLabelText('Código de confirmação'),'123456')
  await ui.click(screen.getByRole('button',{name:'confirmar código'}))
  expect(await screen.findByText('45%')).toBeVisible()
  expect(screen.getByRole('link',{name:'falar com o scrum master'})).toHaveAttribute('href',draft.whatsapp_url)
}, 15000)
test('restores profiles and stores pasted handle with independent authorization and github skip',async()=>{
  const ui=userEvent.setup()
  vi.mocked(api.getCandidate).mockResolvedValue({...draft,current_step:'profiles'})
  vi.mocked(api.saveStep).mockResolvedValue({...draft,current_step:'origin',revision:2,fields:{...draft.fields!,linkedin:'https://linkedin.com/in/example',github_skip_confirmed:true}})
  page()
  const linkedin=await screen.findByLabelText(/LinkedIn/)
  await ui.click(linkedin)
  await ui.paste('https://www.linkedin.com/in/example/')
  expect(linkedin).toHaveValue('example')
  await ui.click(screen.getByLabelText(/Confirmo que quero continuar sem ele/))
  await ui.click(screen.getByLabelText('external_profiles'))
  await ui.click(screen.getByRole('button',{name:'continuar'}))
  await waitFor(()=>expect(api.saveStep).toHaveBeenCalledWith('profiles',expect.objectContaining({linkedin:'example',github_skip_confirmed:true,consents:{external_profiles:'v1'}})))
  expect(await screen.findByText('75%')).toBeVisible()
})
test('origin allows custom text and matches any word in suggestions',async()=>{
  const ui=userEvent.setup()
  vi.mocked(api.getCandidate).mockResolvedValue({...draft,current_step:'origin'})
  vi.mocked(api.saveStep).mockResolvedValue({...draft,current_step:'terms',revision:2})
  page()
  const origin=await screen.findByLabelText('Como conheceu o gaydevs?')
  await ui.type(origin,'grindr')
  expect(screen.getByText('App de relacionamento (Tinder, Scruff, Grindr etc.)')).toBeInTheDocument()
  await ui.clear(origin)
  await ui.type(origin,'Conversa na faculdade')
  await ui.click(screen.getByLabelText('Não'))
  await ui.click(screen.getByRole('button',{name:'continuar'}))
  await waitFor(()=>expect(api.saveStep).toHaveBeenCalledWith('origin',expect.objectContaining({referral_source:'Conversa na faculdade',collaboration_interest:false})))
})
test('pending restores final state without resubmitting',async()=>{
  vi.mocked(api.getCandidate).mockResolvedValue({...draft,status:'pending',current_step:'submitted'})
  page()
  expect(await screen.findByText('100%')).toBeVisible()
  expect(screen.getByRole('heading',{name:'candidatura enviada!'})).toBeVisible()
  expect(api.submitApplication).not.toHaveBeenCalled()
})

test('requires each consent independently and submits from the saved ready step',async()=>{
  const ui=userEvent.setup()
  vi.mocked(api.getCandidate).mockResolvedValue({...draft,current_step:'terms',revision:4})
  vi.mocked(api.saveStep).mockResolvedValue({...draft,current_step:'ready',revision:5})
  vi.mocked(api.submitApplication).mockResolvedValue({...draft,status:'pending',current_step:'submitted',revision:6})
  page()
  await screen.findByRole('heading',{name:'nossos combinados'})
  for(const c of terms.consents) expect(screen.getByLabelText(c.key)).not.toBeChecked()
  await ui.click(screen.getByRole('button',{name:'continuar'}))
  expect(api.saveStep).not.toHaveBeenCalled()
  for(const c of terms.consents) await ui.click(screen.getByLabelText(c.key))
  await ui.click(screen.getByRole('button',{name:'continuar'}))
  await screen.findByRole('heading',{name:'tudo pronto?'})
  expect(api.saveStep).toHaveBeenCalledWith('terms',{revision:4,consents:Object.fromEntries(terms.consents.map(c=>[c.key,'v1']))})
  await ui.click(screen.getByRole('button',{name:'enviar candidatura'}))
  expect(await screen.findByText('100%')).toBeVisible()
  expect(api.submitApplication).toHaveBeenCalledWith(5)
})
